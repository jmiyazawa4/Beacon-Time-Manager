const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const context={window:{},Intl,Date,TextEncoder,Map,Error,Object,Number,String};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../calendar-import.js'),'utf8'),context);
const parse=context.window.BeaconICS.parse;
const calendar=(...events)=>'BEGIN:VCALENDAR\r\n'+events.map(e=>'BEGIN:VEVENT\r\n'+e+'\r\nEND:VEVENT').join('\r\n')+'\r\nEND:VCALENDAR';
const event=(start,extra='')=>'UID:x\r\nDTSTART'+start+'\r\nSUMMARY:Fixture\r\n'+extra;
assert.equal(parse(calendar(event(':20260115T120000'))).events[0].start,'2026-01-15T20:00:00.000Z');
assert.equal(parse(calendar(event(':20260715T120000'))).events[0].start,'2026-07-15T19:00:00.000Z');
assert.equal(parse(calendar(event(';TZID="America/New_York":20260115T120000'))).events[0].start,'2026-01-15T17:00:00.000Z');
assert.equal(parse(calendar(event(':20261101T013000'))).events[0].start,'2026-11-01T08:30:00.000Z');
assert.equal(parse(calendar(event(':20260308T023000'))).skipped,1);
assert.equal(parse(calendar(event(':20260230T120000'))).skipped,1);
assert.equal(parse(calendar(event(';TZID=Unknown/Zone:20260115T120000'))).skipped,1);
const allDay=parse(calendar(event(';VALUE=DATE:20260115'))).events[0];
assert.equal(allDay.start,'2026-01-15');assert.equal(allDay.end,'2026-01-16');assert.equal(allDay.allDay,true);
assert.equal(parse(calendar(event(':20260115T200000Z','DTEND:20260115T190000Z'))).skipped,1);
assert.equal(parse(calendar(event(':20260115T200000Z','RRULE:FREQ=WEEKLY'))).skipped,1);
assert.equal(parse(calendar(event(':20260115T200000Z'),event(':20260116T200000Z','STATUS:CANCELLED'))).events.length,1);
assert.equal(parse(calendar(event(':20260115T200000Z'),event(':20260116T200000Z','STATUS:CANCELLED'))).events[0].status,'CANCELLED');
assert.throws(()=>parse('not a calendar'));
assert.throws(()=>parse('x'.repeat(2000001)));
assert.throws(()=>parse(calendar(...Array(2001).fill(event(':20260115T200000Z')))));
console.log('PASS: browser ICS parser timezone/DST validation, all-day bounds, invalid entries, recurring rules, duplicate updates, cancellation, and size/count limits');
